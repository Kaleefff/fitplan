CREATE VIEW workout_log_summary AS
SELECT
    wl.id AS workout_log_id,
    wl.user_id,
    wl.log_date,
    wl.rpe_rating,
    COUNT(DISTINCT wle.id) AS total_exercises,
    COUNT(ws.id) AS total_sets,
    COALESCE(SUM(ws.reps), 0) AS total_reps,
    COALESCE(
        SUM(ws.reps * ws.weight) FILTER (
            WHERE
                ws.completed
        ),
        0
    ) AS total_volume_kg
FROM
    workout_log wl
    LEFT JOIN workout_log_exercise wle ON wle.workout_log_id = wl.id
    LEFT JOIN workout_set ws ON ws.workout_log_exercise_id = wle.id
WHERE
    wl.deleted_at IS NULL
GROUP BY
    wl.id;

