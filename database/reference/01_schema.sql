-- Module 1: User and account

CREATE TABLE app_user (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255),
    name VARCHAR(100) NOT NULL,
    surname VARCHAR(100) NOT NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'Europe/Warsaw',
    registration_date DATE NOT NULL DEFAULT CURRENT_DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE user_profile (
    user_id INT PRIMARY KEY REFERENCES app_user (id) ON DELETE CASCADE,
    age SMALLINT NOT NULL CHECK (age BETWEEN 16 AND 100),
    sex sex_type NOT NULL,
    current_weight NUMERIC(5, 2) NOT NULL CHECK (
        current_weight BETWEEN 30 AND 300
    ),
    height SMALLINT NOT NULL CHECK (height BETWEEN 120 AND 250),
    activity_level_pal NUMERIC(4, 3) NOT NULL CHECK (
        activity_level_pal BETWEEN 1.200 AND 2.500
    ),
    goal goal_type NOT NULL,
    experience_level difficulty_level NOT NULL,
    equipment equipment_type NOT NULL,
    target_value NUMERIC(5, 2) CHECK (
        target_value BETWEEN 30 AND 300
    ),
    tdee INT NOT NULL CHECK (tdee > 0),
    profile_update TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    family_id UUID NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    replaced_by_id BIGINT REFERENCES refresh_token (id) ON DELETE SET NULL,
    CHECK (expires_at > issued_at)
);

CREATE INDEX ix_refresh_token_user_id ON refresh_token (user_id);

CREATE INDEX ix_refresh_token_family_id ON refresh_token (family_id);

CREATE TABLE password_reset_token (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
