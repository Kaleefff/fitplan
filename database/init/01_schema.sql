-- FitPlan Pro: PostgreSQL schema
-- Module 1: User Profile

CREATE TYPE sex_type          AS ENUM ('male', 'female', 'other');

CREATE TYPE goal_type         AS ENUM ('weight_loss', 'muscle_gain', 'strength', 'maintenance', 'general_fitness', 'endurance');

CREATE TYPE notification_type AS ENUM ('meal_reminder', 'training_reminder', 'progress_update', 'achievement', 'motivational');

CREATE TYPE injury_severity   AS ENUM ('mild', 'moderate', 'severe');

CREATE TABLE app_user (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    surname VARCHAR(100) NOT NULL,
    registration_date DATE NOT NULL DEFAULT CURRENT_DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE user_profile (
    user_id INT PRIMARY KEY REFERENCES app_user (id) ON DELETE CASCADE,
    age SMALLINT NOT NULL CHECK (age BETWEEN 13 AND 100),
    sex sex_type NOT NULL,
    current_weight NUMERIC(5, 2) NOT NULL CHECK (current_weight > 0),
    height SMALLINT NOT NULL CHECK (height BETWEEN 100 AND 250),
    activity_level_pal NUMERIC(3, 2) NOT NULL CHECK (
        activity_level_pal BETWEEN 1.20 AND 2.50
    ),
    goal goal_type NOT NULL,
    target_value NUMERIC(5, 2),
    tdee INT NOT NULL CHECK (tdee > 0),
    profile_update TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE notification (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    message_type notification_type NOT NULL,
    scheduled_at TIMESTAMPTZ NOT NULL,
    message TEXT NOT NULL,
    is_sent BOOLEAN NOT NULL DEFAULT FALSE,
    is_dismissed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX ix_notification_user_id ON notification (user_id);

CREATE TABLE injury_type (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name VARCHAR(45) NOT NULL UNIQUE,
    description VARCHAR(250) NOT NULL,
    avg_healing_time_days SMALLINT NOT NULL CHECK (avg_healing_time_days > 0)
);

CREATE TABLE injury (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    injury_type_id INT NOT NULL REFERENCES injury_type (id),
    affected_muscle_group VARCHAR(100) NOT NULL,
    severity injury_severity NOT NULL,
    start_date DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX ix_injury_user_id ON injury (user_id);

CREATE INDEX ix_injury_injury_type_id ON injury (injury_type_id);

-- Module 2: Diet Plan

CREATE TYPE meal_type AS ENUM ('breakfast', 'lunch', 'dinner', 'snack');

CREATE TABLE food_category (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(45) NOT NULL UNIQUE,
    description VARCHAR(250) NOT NULL
);

CREATE TABLE food_item (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    cals_per_100g NUMERIC(5, 2) NOT NULL CHECK (cals_per_100g >= 0),
    protein_per_100g NUMERIC(5, 2) NOT NULL CHECK (
        protein_per_100g BETWEEN 0 AND 100
    ),
    fat_per_100g NUMERIC(5, 2) NOT NULL CHECK (
        fat_per_100g BETWEEN 0 AND 100
    ),
    carbs_per_100g NUMERIC(5, 2) NOT NULL CHECK (
        carbs_per_100g BETWEEN 0 AND 100
    )
);

CREATE TABLE food_item_category (
    food_item_id INT NOT NULL REFERENCES food_item (id) ON DELETE CASCADE,
    food_category_id INT NOT NULL REFERENCES food_category (id) ON DELETE CASCADE,
    PRIMARY KEY (
        food_item_id,
        food_category_id
    )
);

CREATE INDEX ix_food_item_category_category_id ON food_item_category (food_category_id);

CREATE TABLE meal (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_type meal_type NOT NULL,
    meal_order SMALLINT NOT NULL CHECK (meal_order > 0),
    planned_time TIME NOT NULL,
    planned_cals INT NOT NULL CHECK (planned_cals >= 0),
    planned_protein NUMERIC(6, 2) NOT NULL CHECK (planned_protein >= 0),
    planned_fat NUMERIC(6, 2) NOT NULL CHECK (planned_fat >= 0),
    planned_carbs NUMERIC(6, 2) NOT NULL CHECK (planned_carbs >= 0)
);

CREATE TABLE meal_food_item (
    meal_id INT NOT NULL REFERENCES meal (id) ON DELETE CASCADE,
    food_item_id INT NOT NULL REFERENCES food_item (id),
    grams NUMERIC(6, 1) NOT NULL CHECK (grams > 0),
    PRIMARY KEY (meal_id, food_item_id)
);

CREATE INDEX ix_meal_food_item_food_item_id ON meal_food_item (food_item_id);

CREATE TABLE diet_plan (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    name VARCHAR(45) NOT NULL,
    goal goal_type NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    daily_cal_goal INT NOT NULL CHECK (daily_cal_goal > 0),
    protein_goal NUMERIC(6, 2) NOT NULL CHECK (protein_goal >= 0),
    fat_goal NUMERIC(6, 2) NOT NULL CHECK (fat_goal >= 0),
    carbs_goal NUMERIC(6, 2) NOT NULL CHECK (carbs_goal >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    dietary_restrictions VARCHAR(500),
    CHECK (end_date >= start_date)
);

CREATE INDEX ix_diet_plan_user_id ON diet_plan (user_id);

CREATE UNIQUE INDEX ux_diet_plan_one_active ON diet_plan (user_id)
WHERE
    is_active;

CREATE TABLE diet_plan_meal (
    diet_plan_id INT NOT NULL REFERENCES diet_plan (id) ON DELETE CASCADE,
    meal_id INT NOT NULL REFERENCES meal (id) ON DELETE CASCADE,
    PRIMARY KEY (diet_plan_id, meal_id)
);

CREATE INDEX ix_diet_plan_meal_meal_id ON diet_plan_meal (meal_id);

CREATE TABLE nutrition_log (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    log_date DATE NOT NULL,
    meal_type meal_type NOT NULL,
    meal_photo_url VARCHAR(250),
    ai_confidence NUMERIC(3, 2) CHECK (ai_confidence BETWEEN 0 AND 1),
    ai_was_edited BOOLEAN,
    actual_cals NUMERIC(6, 2) NOT NULL CHECK (actual_cals >= 0),
    actual_protein NUMERIC(6, 2) NOT NULL CHECK (actual_protein >= 0),
    actual_fat NUMERIC(6, 2) NOT NULL CHECK (actual_fat >= 0),
    actual_carbs NUMERIC(6, 2) NOT NULL CHECK (actual_carbs >= 0),
    hunger_level_before SMALLINT NOT NULL CHECK (
        hunger_level_before BETWEEN 1 AND 10
    ),
    hunger_level_after SMALLINT NOT NULL CHECK (
        hunger_level_after BETWEEN 1 AND 10
    ),
    logged_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        (ai_confidence IS NULL) = (ai_was_edited IS NULL)
    )
);

CREATE INDEX ix_nutrition_log_user_date ON nutrition_log (user_id, log_date);

CREATE TABLE nutrition_log_food_item (
    nutrition_log_id INT NOT NULL REFERENCES nutrition_log (id) ON DELETE CASCADE,
    food_item_id INT NOT NULL REFERENCES food_item (id),
    grams NUMERIC(6, 1) NOT NULL CHECK (grams > 0),
    PRIMARY KEY (
        nutrition_log_id,
        food_item_id
    )
);

CREATE INDEX ix_nutrition_log_food_item_food_item_id ON nutrition_log_food_item (food_item_id);
