"""Exercise coverage report (DB-03).

Reads the exercise seed in database/seed/ and writes database/seed/exercise_coverage.md:
eligible exercises per muscle group, level and equipment (algorithms.md 4.2), the gaps of
each goal's main groups (algorithms.md 3) and what the injury exclusions leave (rule 1 of
algorithms.md 4.3; rules 2 and 3 depend on the muscle group the user picks).

Run from backend/ after changing exercise.csv or injury_type_excluded_exercise.csv:
    uv run python -m app.db.exercise_coverage
A test fails when the committed report is out of date or a goal has a gap.
"""

import csv
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

from app.db.seed import SEED_DIR
from app.domain.constants import ALL_GROUPS, EQUIPMENT_ORDER, LEVEL_ORDER, MAIN_GROUPS, Goal

REPORT_NAME = "exercise_coverage.md"
CELLS = [(level, tier) for level in LEVEL_ORDER for tier in EQUIPMENT_ORDER]
SHORT = {"beginner": "B", "intermediate": "I", "advanced": "A"}


@dataclass(frozen=True)
class Item:
    name: str
    group: str
    level: int
    tier: int


def read_csv(seed_dir: Path, name: str) -> list[dict[str, str]]:
    with (seed_dir / f"{name}.csv").open(encoding="utf-8", newline="") as file:
        return list(csv.DictReader(file))


def read_items(seed_dir: Path) -> list[Item]:
    return [
        Item(
            row["name"],
            row["primary_group"],
            LEVEL_ORDER.index(row["difficulty_level"]),
            EQUIPMENT_ORDER.index(row["equipment"]),
        )
        for row in read_csv(seed_dir, "exercise")
    ]


def eligible(items: list[Item], group: str, level: int, tier: int, excluded=frozenset()) -> int:
    """Exercises of `group` a user of `level` with `tier` equipment may get (4.2)."""
    return sum(
        1
        for i in items
        if i.group == group and i.level <= level and i.tier <= tier and i.name not in excluded
    )


def gaps(items: list[Item]) -> dict[Goal, list[str]]:
    """Main-group cells without an eligible exercise, per goal."""
    return {
        goal: [
            f"{group} ({level}, {tier})"
            for group in MAIN_GROUPS[goal]
            for level, tier in CELLS
            if not eligible(items, group, LEVEL_ORDER.index(level), EQUIPMENT_ORDER.index(tier))
        ]
        for goal in Goal
    }


def table(items: list[Item], count) -> list[str]:
    header = "| Group | " + " | ".join(f"{SHORT[level]} {tier}" for level, tier in CELLS) + " |"
    lines = [header, "| --- |" + " ---: |" * len(CELLS)]
    for group in ALL_GROUPS:
        counts = [
            str(count(items, group, LEVEL_ORDER.index(level), EQUIPMENT_ORDER.index(tier)))
            for level, tier in CELLS
        ]
        lines.append(f"| {group} | " + " | ".join(counts) + " |")
    return lines


def exact(items: list[Item], group: str, level: int, tier: int) -> int:
    return sum(1 for i in items if i.group == group and i.level == level and i.tier == tier)


def report(seed_dir: Path = SEED_DIR) -> str:
    items = read_items(seed_dir)
    excluded: dict[str, set[str]] = defaultdict(set)
    for row in read_csv(seed_dir, "injury_type_excluded_exercise"):
        excluded[row["injury_type"]].add(row["exercise"])

    lines = [
        "# Exercise coverage",
        "",
        "Generated by `uv run python -m app.db.exercise_coverage` (run from `backend/`) from",
        "`exercise.csv` and `injury_type_excluded_exercise.csv`; do not edit by hand.",
        f"{len(items)} exercises. Columns: B, I, A = beginner, intermediate, advanced;"
        " none, home, gym = equipment.",
        "",
        "## Eligible exercises (algorithms.md 4.2)",
        "",
        "What the generator can choose from per primary group: difficulty at most the level,"
        " equipment at most the tier.",
        "",
        *table(items, eligible),
        "",
        "## Exercises defined at each level and tier",
        "",
        "0 means users of that level and tier get an easier or lower-tier exercise.",
        "",
        *table(items, exact),
        "",
        "## Gaps per goal (algorithms.md 3)",
        "",
    ]
    goal_gaps = gaps(items)
    for goal in Goal:
        found = goal_gaps[goal]
        lines.append(f"- {goal.value}: {', '.join(found) if found else 'none'}")

    lines += [
        "",
        "## Injury exclusions (algorithms.md 4.3, rule 1)",
        "",
        "Groups left without an exercise even at the advanced level, by the exclusion list"
        " alone. Such a group is skipped with reason `injury`; rules 2 and 3 (the affected"
        " group the user picks) can skip more.",
        "",
        "| Injury type | Excluded | Groups left empty |",
        "| --- | ---: | --- |",
    ]
    advanced = len(LEVEL_ORDER) - 1
    for row in read_csv(seed_dir, "injury_type"):
        names = excluded.get(row["type_name"], set())
        empty = []
        for group in ALL_GROUPS:
            tiers = [
                tier.value
                for t, tier in enumerate(EQUIPMENT_ORDER)
                if not eligible(items, group, advanced, t, names)
            ]
            if tiers:
                empty.append(f"{group} ({', '.join(tiers)})")
        lines.append(f"| {row['type_name']} | {len(names)} | {', '.join(empty) or '-'} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    path = SEED_DIR / REPORT_NAME
    path.write_text(report(), encoding="utf-8", newline="\n")
    print(f"wrote {path}")
    found = {goal: cells for goal, cells in gaps(read_items(SEED_DIR)).items() if cells}
    for goal, cells in found.items():
        print(f"gap in {goal.value}: {', '.join(cells)}", file=sys.stderr)
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
